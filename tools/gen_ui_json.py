#!/usr/bin/env python3
"""Usage: gen_ui_json.py module.json out.h

The Schwung UI does not read ui_hierarchy / chain_params from module.json: it asks the
loaded DSP for them through get_param(). This derives both documents from module.json
and emits them as C string constants, so the two can never drift apart.

Formats follow the installed modules (chiptune, braids): compact JSON, a hierarchy of
levels each with `knobs` and `params`, and chain_params entries with key/name/type and
min/max/step or options."""
import json
import sys

args = [a for a in sys.argv[1:] if not a.startswith("--json=")]
json_dir = next((a.split("=", 1)[1] for a in sys.argv[1:] if a.startswith("--json=")), None)
src, dst = args[0], args[1]
with open(src, encoding="utf-8") as f:
    m = json.load(f)

levels_in = m["capabilities"]["ui_hierarchy"]["levels"]

# metadata a canvas (custom screen) parameter needs on the host side
CANVAS_KEYS = ("canvas_script", "show_value", "show_footer", "fullscreen_live_ms", "extra_keys", "enterable",
               "as_page", "page_first", "canvas_overlay")

levels_out = {}
chain = []
for lname, level in levels_in.items():
    params_out = []
    for p in level["params"]:
        if "level" in p:                                   # link to another page
            params_out.append({"level": p["level"], "label": p["label"]})
            continue
        entry = {"key": p["key"]}
        if "short_name" in p:
            entry["short_name"] = p["short_name"]
        entry["label"] = p["label"]
        if p["type"] == "canvas":
            entry["type"] = "canvas"
            entry.update({k: p[k] for k in CANVAS_KEYS if k in p})
        params_out.append(entry)

        c = {"key": p["key"], "name": p["label"], "type": p["type"]}
        if p["type"] == "enum":
            c["options"] = "@PAD_OPTIONS@" if p.get("dynamic_options") else p["options"]   # filled in by the DSP at runtime
        elif p["type"] == "canvas":
            c.update({k: p[k] for k in CANVAS_KEYS if k in p})
        elif p["type"] == "filepath":
            for k in ("root", "start_path", "filter"):
                if k in p:
                    c[k] = p[k]
        else:
            c["min"] = p["min"]
            c["max"] = p["max"] if "max" in p else "@MAX@"  # max_param: filled in with the real count at runtime
            if "step" in p:
                c["step"] = p["step"]
            elif p["type"] == "int":
                c["step"] = 1
        if p.get("access") == "read":
            c["access"] = "read"
        chain.append(c)
    levels_out[lname] = {"children": None, "label": level["label"], "knobs": level["knobs"], "params": params_out}

# parameters the host reads but never lists as knobs (feeds that a canvas page draws from)
for feed in m["capabilities"].get("feeds", []):
    chain.append({k: feed[k] for k in ("key", "name", "type", "access") if k in feed})

hierarchy = {"modes": None, "levels": levels_out}


def compact(o):
    return json.dumps(o, separators=(",", ":"), ensure_ascii=True)


def c_literal(name, text):
    # must be valid JSON once the runtime placeholders are filled
    json.loads(text.replace("@SUBTUNE_MAX@", "256").replace("@SIDS_DIR@", "/x/sids").replace("@PAD_OPTIONS@", '["Saw"]'))
    esc = text.replace("\\", "\\\\").replace('"', '\\"')
    return f'static const char {name}[] = "{esc}";\n'


h, c = compact(hierarchy), compact(chain).replace('"max":"@MAX@"', '"max":@SUBTUNE_MAX@').replace('"options":"@PAD_OPTIONS@"', '"options":@PAD_OPTIONS@')
assert c.count("@SUBTUNE_MAX@") <= 1, "only one max_param (subtune) is supported"
# a host read buffer is 4096 bytes at the smallest; plugin.c fills the placeholders (the sids folder, the subtune count) and trims the
# instrument list to fit CHAIN_PARAMS_BUDGET, so the static part has to leave room for the rest
if len(h) > 3800 or len(c) > 3800:
    sys.exit(f"UI JSON too large for a host get_param buffer: hierarchy {len(h)}, chain_params {len(c)}")

with open(dst, "w", newline="\n") as f:
    f.write("/* generated by tools/gen_ui_json.py from module.json: do not edit */\n")
    f.write(c_literal("ui_hierarchy_json", h))
    f.write(c_literal("chain_params_json", c))
if json_dir:
    import os
    os.makedirs(json_dir, exist_ok=True)
    fill = lambda t: t.replace("@SUBTUNE_MAX@", "19").replace("@SIDS_DIR@", "/data/UserData/schwung/modules/sound_generators/tinysid/sids").replace("@PAD_OPTIONS@", '["Lead"]')
    with open(os.path.join(json_dir, "ui_hierarchy.json"), "w", newline="\n") as f:
        f.write(fill(h))
    with open(os.path.join(json_dir, "chain_params.json"), "w", newline="\n") as f:
        f.write(fill(c))
    with open(os.path.join(json_dir, "capabilities.json"), "w", newline="\n") as f:
        json.dump(m["capabilities"], f)
print(f"ui_hierarchy {len(h)} bytes, chain_params {len(c)} bytes")
