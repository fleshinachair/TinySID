#!/usr/bin/env python3
"""Usage: embed_sid.py in.sid out.h -- embeds a PSID file as the default tune."""
import sys

with open(sys.argv[1], "rb") as f:
    data = f.read()
if data[:4] != b"PSID":
    sys.exit(f"{sys.argv[1]}: not a PSID file")
with open(sys.argv[2], "w", newline="\n") as f:
    f.write(f"/* generated by tools/embed_sid.py from {sys.argv[1].split('/')[-1]} */\n")
    f.write("static const unsigned char default_sid_data[] = {\n")
    for i in range(0, len(data), 16):
        f.write("    " + ", ".join(f"0x{b:02X}" for b in data[i:i + 16]) + ",\n")
    f.write("};\n")
    f.write(f"static const unsigned int default_sid_len = {len(data)};\n")
